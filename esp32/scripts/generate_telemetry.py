#!/usr/bin/env python3
"""CLI tool to synthesize the ESP32 Embedded Dataset C header/source artifacts."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import sys
from typing import Sequence

SCRIPTS_DIR = Path(__file__).resolve().parent
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

from telemetry_profiles import (  # noqa: E402
    EntropyProfile,
    PAYLOAD_SIZE,
    RECORD_SIZE,
    RECORDS_PER_FRAME,
    generate_dataset,
    load_profile_config,
)

_PROFILE_ENUM_SYMBOLS: dict[EntropyProfile, str] = {
    EntropyProfile.QUIESCENT: "TELEMETRY_PROFILE_QUIESCENT",
    EntropyProfile.DYNAMIC: "TELEMETRY_PROFILE_DYNAMIC",
    EntropyProfile.CHAOTIC: "TELEMETRY_PROFILE_CHAOTIC",
}


def _format_payload_bytes(payload: bytes, bytes_per_line: int = 16) -> str:
    lines: list[str] = []
    for offset in range(0, len(payload), bytes_per_line):
        chunk = payload[offset : offset + bytes_per_line]
        hex_vals = ", ".join(f"0x{b:02X}U" for b in chunk)
        lines.append(f"            {hex_vals}")
    return ",\n".join(lines)


def _format_dataset_initializer(dataset: Sequence[tuple[EntropyProfile, bytes]]) -> str:
    entries: list[str] = []
    for idx, (profile, payload) in enumerate(dataset):
        enum_sym = _PROFILE_ENUM_SYMBOLS[profile]
        byte_block = _format_payload_bytes(payload)
        entries.append(
            f"    /* Frame {idx}: {profile.label} */\n"
            f"    {{\n"
            f"        .profile = {enum_sym},\n"
            f"        .payload = {{\n"
            f"{byte_block}\n"
            f"        }}\n"
            f"    }}"
        )
    return ",\n".join(entries)


def _format_profile_name_fn(qualifier: str) -> list[str]:
    return [
        f"{qualifier}const char *telemetry_profile_name(telemetry_entropy_profile_t profile) {{",
        "    switch (profile) {",
        "        case TELEMETRY_PROFILE_QUIESCENT:",
        '            return "Quiescent";',
        "        case TELEMETRY_PROFILE_DYNAMIC:",
        '            return "Dynamic";',
        "        case TELEMETRY_PROFILE_CHAOTIC:",
        '            return "Chaotic";',
        "        default:",
        '            return "Unknown";',
        "    }",
        "}",
    ]


def format_c_header(
    dataset: Sequence[tuple[EntropyProfile, bytes]],
    seed: int,
    frames_per_profile: int,
    header_only: bool = True,
) -> str:
    """Render a self-contained C11/C++ compatible header for the Embedded Dataset."""
    total_frames = len(dataset)
    lines: list[str] = [
        "/**",
        " * @file telemetry_dataset.h",
        " * @brief Auto-generated flash-resident Embedded Dataset for ESP32 SPI injector.",
        " *",
        " * Generated by esp32/scripts/generate_telemetry.py. Do not edit manually.",
        " */",
        "",
        "#ifndef TELEMETRY_DATASET_H",
        "#define TELEMETRY_DATASET_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f"#define TELEMETRY_DATASET_SEED        {seed}U",
        f"#define TELEMETRY_FRAMES_PER_PROFILE  {frames_per_profile}U",
        f"#define TELEMETRY_DATASET_FRAME_COUNT {total_frames}U",
        f"#define TELEMETRY_PAYLOAD_SIZE        {PAYLOAD_SIZE}U",
        f"#define TELEMETRY_RECORD_SIZE         {RECORD_SIZE}U",
        f"#define TELEMETRY_RECORDS_PER_FRAME   {RECORDS_PER_FRAME}U",
        "",
        "typedef enum {",
        "    TELEMETRY_PROFILE_QUIESCENT = 0,",
        "    TELEMETRY_PROFILE_DYNAMIC   = 1,",
        "    TELEMETRY_PROFILE_CHAOTIC   = 2",
        "} telemetry_entropy_profile_t;",
        "",
        "typedef struct {",
        "    telemetry_entropy_profile_t profile;",
        "    const uint8_t payload[TELEMETRY_PAYLOAD_SIZE];",
        "} telemetry_dataset_entry_t;",
        "",
    ]

    if header_only:
        lines.extend(_format_profile_name_fn("static inline "))
        lines.extend(
            [
                "",
                "#if defined(__GNUC__) || defined(__clang__)",
                "#define TELEMETRY_DATASET_UNUSED_ATTR __attribute__((unused))",
                "#else",
                "#define TELEMETRY_DATASET_UNUSED_ATTR",
                "#endif",
                "",
                "static const telemetry_dataset_entry_t "
                "g_telemetry_dataset[TELEMETRY_DATASET_FRAME_COUNT]",
                "    TELEMETRY_DATASET_UNUSED_ATTR = {",
                _format_dataset_initializer(dataset),
                "};",
            ]
        )
    else:
        lines.extend(
            [
                "const char *telemetry_profile_name(telemetry_entropy_profile_t profile);",
                "",
                "extern const telemetry_dataset_entry_t "
                "g_telemetry_dataset[TELEMETRY_DATASET_FRAME_COUNT];",
            ]
        )

    lines.extend(
        [
            "",
            "#ifdef __cplusplus",
            "}",
            "#endif",
            "",
            "#endif /* TELEMETRY_DATASET_H */",
            "",
        ]
    )
    return "\n".join(lines)


def format_c_source(
    dataset: Sequence[tuple[EntropyProfile, bytes]],
    header_include: str,
) -> str:
    """Render the companion C11 source file defining the flash .rodata dataset."""
    lines: list[str] = [
        "/**",
        " * @file telemetry_dataset.c",
        " * @brief Auto-generated flash-resident Embedded Dataset definitions.",
        " *",
        " * Generated by esp32/scripts/generate_telemetry.py. Do not edit manually.",
        " */",
        "",
        f'#include "{header_include}"',
        "",
    ]
    lines.extend(_format_profile_name_fn(""))
    lines.extend(
        [
            "",
            "const telemetry_dataset_entry_t g_telemetry_dataset[TELEMETRY_DATASET_FRAME_COUNT] = {",
            _format_dataset_initializer(dataset),
            "};",
            "",
        ]
    )
    return "\n".join(lines)


def write_dataset_artifacts(
    out_header: Path,
    seed: int = 42,
    frames_per_profile: int = 10,
    config_path: Path | None = None,
    out_source: Path | None = None,
) -> list[tuple[EntropyProfile, bytes]]:
    """Generate the Embedded Dataset and write the C header (and optional C source)."""
    if seed < 0:
        raise ValueError(f"seed must be >= 0, got {seed}")

    cfg = load_profile_config(config_path)
    dataset = generate_dataset(seed=seed, frames_per_profile=frames_per_profile, config=cfg)

    header_only = out_source is None
    header_text = format_c_header(
        dataset=dataset,
        seed=seed,
        frames_per_profile=frames_per_profile,
        header_only=header_only,
    )

    source_text: str | None = None
    if out_source is not None:
        rel_header = Path(os.path.relpath(out_header, start=out_source.parent)).as_posix()
        source_text = format_c_source(dataset=dataset, header_include=rel_header)

    out_header.parent.mkdir(parents=True, exist_ok=True)
    out_header.write_text(header_text, encoding="utf-8")

    if out_source is not None and source_text is not None:
        out_source.parent.mkdir(parents=True, exist_ok=True)
        out_source.write_text(source_text, encoding="utf-8")

    return dataset


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate flash-resident Embedded Dataset C artifacts for the ESP32 injector."
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Deterministic PRNG seed (default: 42).",
    )
    parser.add_argument(
        "--frames-per-profile",
        type=int,
        default=10,
        help="Number of 1024 B frames per Entropy Profile (default: 10).",
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=None,
        help="Optional JSON file overriding profile sensor ranges/parameters.",
    )
    parser.add_argument(
        "--out-header",
        type=Path,
        required=True,
        help="Output path for the generated C header file.",
    )
    parser.add_argument(
        "--out-source",
        type=Path,
        default=None,
        help="Optional output path for a companion C source file.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point returning 0 on success or non-zero on validation/I/O error."""
    parser = _build_arg_parser()
    args = parser.parse_args(argv)
    try:
        write_dataset_artifacts(
            out_header=args.out_header,
            seed=args.seed,
            frames_per_profile=args.frames_per_profile,
            config_path=args.config,
            out_source=args.out_source,
        )
    except (ValueError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

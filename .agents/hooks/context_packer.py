#!/usr/bin/env python3
"""context_packer.py: Bulk repository context assembler for Gemini 3.8 Flash.

Bundles architectural invariants, memory indices, register maps, RTL cores,
and firmware drivers into a single, cohesive, formatted markdown document.
Takes advantage of Gemini 3.8 Flash's 1M+ token context window.

Usage:
  python3 .agents/hooks/context_packer.py [--mode {minimal,hardware,firmware,full}] [--summary] [--output <file>]
"""
import argparse
import sys
from pathlib import Path

